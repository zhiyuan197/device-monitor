param(
    [string] $TlsDir = "config/tls"
)

$ErrorActionPreference = "Stop"
$projectRoot = Split-Path -Parent $PSScriptRoot
$workspaceRoot = Split-Path -Parent $projectRoot

$jdkRoot = Join-Path $workspaceRoot ".tools\jdk-17"
$keytool = $null
if (Test-Path -LiteralPath $jdkRoot) {
    $jdk = Get-ChildItem -LiteralPath $jdkRoot -Directory |
        Where-Object { Test-Path -LiteralPath (Join-Path $_.FullName "bin\keytool.exe") } |
        Select-Object -First 1
    if ($jdk) {
        $keytool = Join-Path $jdk.FullName "bin\keytool.exe"
    }
}
if (-not $keytool) {
    $systemKeytool = Get-Command keytool -ErrorAction SilentlyContinue
    if (-not $systemKeytool) {
        throw "keytool was not found. Install a JDK or place portable tools under .tools."
    }
    $keytool = $systemKeytool.Source
}

$tlsPath = Join-Path $projectRoot $TlsDir
New-Item -ItemType Directory -Force -Path $tlsPath | Out-Null
$keystore = Join-Path $tlsPath "server-keystore.p12"
$truststore = Join-Path $tlsPath "client-truststore.p12"
$properties = Join-Path $tlsPath "tls.properties"
$password = "device-monitor-demo"

if (-not (Test-Path -LiteralPath $keystore)) {
    & $keytool -genkeypair `
        -alias device-monitor `
        -keyalg RSA -keysize 2048 -validity 3650 `
        -storetype PKCS12 `
        -keystore $keystore `
        -storepass $password -keypass $password `
        -dname "CN=device-monitor-local, OU=CourseDemo, O=DeviceWatch, L=Local, C=CN" `
        -ext "SAN=DNS:localhost,IP:127.0.0.1"
    if ($LASTEXITCODE -ne 0) {
        throw "keytool failed to generate the server keystore"
    }
}

if (-not (Test-Path -LiteralPath $truststore)) {
    & $keytool -exportcert `
        -alias device-monitor `
        -keystore $keystore `
        -storepass $password `
        -rfc -file (Join-Path $tlsPath "server-cert.pem")
    if ($LASTEXITCODE -ne 0) {
        throw "keytool failed to export the certificate"
    }
    & $keytool -importcert `
        -noprompt `
        -alias device-monitor `
        -keystore $truststore `
        -storetype PKCS12 `
        -storepass $password `
        -file (Join-Path $tlsPath "server-cert.pem")
    if ($LASTEXITCODE -ne 0) {
        throw "keytool failed to build the client truststore"
    }
}

@(
    "# Generated by scripts/init-keystore.ps1 - local demo only, do not commit"
    "tls.password=$password"
) | Set-Content -LiteralPath $properties -Encoding utf8

Write-Output "keystore=$keystore"
Write-Output "truststore=$truststore"
Write-Output "properties=$properties"
